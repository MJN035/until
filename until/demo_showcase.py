"""샘플 과제 픽스처 — `/simple?demo=1` 프리필용(결정적·LLM 0).

방문자가 자기 과제를 붙여넣기 전에 흐름을 한 번 돌려 볼 수 있도록, 볼륨형 과제
지시문 하나를 고정해 둔다. 마감은 렌더 시점에 오늘+21일로 계산해 낡지 않게 하고,
그 덕에 체크포인트 플랜(볼륨 게이트)도 항상 발동한다.

작동 예시 페이지(`/demo`)는 2026-08-21에 없앴다 — 소개(`/about`)가 같은 5단계를
이미 보여 준다. 그때 쓰던 초안·답변·완성본 픽스처도 함께 지웠고, 프리필에 필요한
과제 지시문만 남았다.
"""
from __future__ import annotations

from datetime import date, timedelta


def demo_deadline() -> date:
    """데모 마감 = 오늘+21일 — 체크포인트 플랜(볼륨 게이트)이 항상 발동."""
    return date.today() + timedelta(days=21)


def demo_assignment_text() -> str:
    """볼륨형 데모 과제 원문(간단 모드 프리필과 쇼케이스가 공유)."""
    d = demo_deadline()
    return (
        "[기말 조사 보고서] 디지털 전환이 우리 일상 공간(캠퍼스·동네·일터 중 택1)을 "
        "어떻게 바꾸고 있는지 조사하고, 본인의 관찰과 자료를 근거로 분석 보고서를 "
        "작성하세요.\n\n"
        "요구사항:\n"
        "- 분량: 3000자 이상 (공백 제외)\n"
        "- 실제 사례 2개 이상과 관찰 근거 포함, 인용 출처 표기\n"
        "- 분석 대상 공간을 정하고 그 이유를 밝힐 것\n"
        f"- 마감: {d.year}년 {d.month}월 {d.day}일 23:59, eTL 제출\n"
    )


